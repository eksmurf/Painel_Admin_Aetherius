'use strict';
// Explicitly targets a disposable local MariaDB instance, never database.local.json.
const assert = require('node:assert/strict');
const fs = require('node:fs'); const path = require('node:path'); const { randomUUID } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const targetRoot = path.resolve(process.env.AETHERIUS_SOURCE || path.join(__dirname, '../../Aetherius-RP-Local'));
if (process.env.ADMIN_TEST_DB_PORT !== '34327') throw new Error('Start an isolated MariaDB on 127.0.0.1:34327 and set ADMIN_TEST_DB_PORT=34327.');
const mysqlPath = require.resolve(path.join(targetRoot, 'aetherius/gamemode/node_modules/mysql2/promise'));
const mysql = require(mysqlPath);
const { createMysqlStore } = require('../gamemode/mysql-store.cjs');
const transactionService = require(path.join(targetRoot, 'aetherius/gamemode/core/transaction-service.js'));
const database = `aap_test_${Date.now()}`;
const options = { host: '127.0.0.1', port: 34327, user: 'root', password: '', database, connectionLimit: 8 };
(async () => {
  const connection = await mysql.createConnection({ ...options, database: undefined });
  await connection.query(`CREATE DATABASE ${database} CHARACTER SET utf8mb4`); await connection.end();
  const pool = mysql.createPool(options);
  const db = { query: async (sql, args) => (await pool.execute(sql, args))[0], getConnection: () => pool.getConnection() };
  try {
    const schema = fs.readFileSync(path.join(targetRoot, 'aetherius/packages/database/schema.sql'), 'utf8');
    for (const table of ['accounts', 'characters', 'character_inventory', 'staff_roles', 'inventory_transactions', 'gold_transactions']) {
      const start = schema.indexOf('CREATE TABLE IF NOT EXISTS `' + table + '`');
      assert(start >= 0); const end = schema.indexOf('ENGINE=InnoDB;', start);
      await db.query(schema.slice(start, end + 'ENGINE=InnoDB;'.length));
    }
    await db.query('ALTER TABLE character_inventory ADD UNIQUE KEY char_item(character_id,base_id)');
    const adapter = path.resolve(__dirname, `../artifacts/${database}.cjs`);
    fs.writeFileSync(adapter, `const p=require(${JSON.stringify(mysqlPath)}).createPool(${JSON.stringify(options)});module.exports={getConnection:()=>p.getConnection(),close:()=>p.end()};`);
    execFileSync(process.execPath, [path.resolve(__dirname, '../scripts/migrate.cjs'), adapter], { stdio: 'pipe' });
    await db.query("DELETE FROM aetherius_admin_permissions WHERE role='moderator' AND permission='players.kick'");
    execFileSync(process.execPath, [path.resolve(__dirname, '../scripts/migrate.cjs'), adapter], { stdio: 'pipe' });
    assert.equal((await db.query("SELECT * FROM aetherius_admin_permissions WHERE role='moderator' AND permission='players.kick'")).length, 0);
    console.log('PASS migration does not restore revoked grants');
    await db.query("INSERT INTO accounts(id) VALUES(1),(2)");
    await db.query("INSERT INTO characters(id,account_id,first_name,last_name,status,gold) VALUES(10,1,'Staff','Teste','approved',0),(20,2,'Alvo','Teste','approved',250)");
    await db.query("INSERT INTO staff_roles(account_id,role) VALUES(1,'admin')");
    const store = createMysqlStore({ db, transactionService });
    assert((await store.authorize({ accountId: 1, characterId: 10 })).permissions.includes('economy.adjust'));
    assert.equal(await store.authorize({ accountId: 1, characterId: 20 }), null);
    console.log('PASS authorization binds account and approved character');
    const makeOp = action => ({ requestId: randomUUID(), accountId: 1, characterId: 10, targetAccountId: 2, targetCharacterId: 20, action, reason: 'Teste automatizado isolado', sensitive: false, hash: 'a'.repeat(64) });
    const target = { accountId: 2, characterId: 20 };
    const ctx = { permission: 'economy.adjust', validateSession: () => {}, host: { resolveItem: () => 123, deliverItem: async () => {} }, item: { label: 'Item de teste' } };
    const op = makeOp('economy.setGold');
    const reservations = await Promise.all([store.reserve(op), store.reserve(op)]);
    assert.equal(reservations.filter(r => r.fresh).length, 1);
    console.log('PASS concurrent requests have one durable reservation');
    assert.equal((await store.mutate(op, { amount: 1000 }, target, ctx)).status, 'succeeded');
    assert.equal((await db.query('SELECT gold FROM characters WHERE id=20'))[0].gold, 1000);
    assert.equal((await db.query('SELECT delta FROM gold_transactions'))[0].delta, 750);
    assert.equal((await store.reserve(op)).result.status, 'succeeded');
    console.log('PASS absolute RP balance and ledger commit with receipt');
    const broken = createMysqlStore({ db, transactionService: { tx: { ...transactionService.tx, recordGoldLedger: async () => { throw new Error('simulated ledger failure'); } } } });
    const rollbackOp = makeOp('economy.setGold'); await broken.reserve(rollbackOp);
    await assert.rejects(broken.mutate(rollbackOp, { amount: 25 }, target, ctx), /ledger failure/);
    assert.equal((await db.query('SELECT gold FROM characters WHERE id=20'))[0].gold, 1000);
    assert.equal((await broken.reserve(rollbackOp)).result, null);
    console.log('PASS ledger failure rolls back money and completion');
    await db.query("DELETE FROM aetherius_admin_permissions WHERE role='admin' AND permission='economy.adjust'");
    const revoked = makeOp('economy.setGold'); await store.reserve(revoked);
    await assert.rejects(store.mutate(revoked, { amount: 50 }, target, ctx), { code: 'FORBIDDEN' });
    console.log('PASS transaction checks current permission under lock');
    const itemOp = makeOp('inventory.grant'); await store.reserve(itemOp);
    const itemContext = { ...ctx, permission: 'inventory.grant', host: { ...ctx.host, deliverItem: async () => { throw new Error('game disconnected'); } } };
    assert.equal((await store.mutate(itemOp, { quantity: 3 }, target, itemContext)).status, 'unknown');
    assert.equal((await db.query('SELECT count FROM character_inventory WHERE character_id=20 AND base_id=123'))[0].count, 3);
    assert.equal((await store.reserve(itemOp)).result.data.persisted, true);
    console.log('PASS failed game delivery retains grant and unknown receipt');
    const auditFailDb = { ...db, query: async (sql, args) => { if (sql.startsWith('UPDATE aetherius_admin_operations')) throw new Error('audit unavailable'); return db.query(sql, args); } };
    const auditFailStore = createMysqlStore({ db: auditFailDb, transactionService });
    const uncertainOp = makeOp('inventory.grant'); await auditFailStore.reserve(uncertainOp);
    assert.equal((await auditFailStore.mutate(uncertainOp, { quantity: 1 }, target, { ...ctx, permission: 'inventory.grant' })).status, 'unknown');
    assert.equal((await store.reserve(uncertainOp)).result.status, 'unknown');
    console.log('PASS failed final audit never reports confirmed delivery');
    const secret = { ...makeOp('identity.reveal'), sensitive: true }; await store.reserve(secret); await store.finish(secret, { status: 'succeeded', data: { identity: 'CONFIDENTIAL' } });
    assert.equal((await store.audit({ action: 'identity.reveal' }, false)).total, 0);
    const audit = await store.audit({ action: 'identity.reveal' }, true); assert.equal(audit.total, 1); assert(!JSON.stringify(audit).includes('CONFIDENTIAL'));
    console.log('PASS sensitive audit filtering and identity redaction');
    const retired = makeOp('character.retire'); await store.reserve(retired);
    await store.mutate(retired, {}, target, { ...ctx, permission: 'characters.permakill' });
    assert.equal((await db.query('SELECT status FROM characters WHERE id=20'))[0].status, 'retired');
    assert.equal((await store.reserve(retired)).result.status, 'succeeded');
    console.log('PASS retirement and receipt commit together');
    console.log(`10 integration scenarios passed; isolated database ${database}`);
  } finally { await pool.end(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
